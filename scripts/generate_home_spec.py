"""Generate importable artwork data without runtime filesystem reads.

Run after changing HOME_SPEC in cards.js. CI checks byte-for-byte freshness.
"""
import argparse
import json
from pathlib import Path
from pprint import pformat
import re

ROOT = Path(__file__).resolve().parents[1] / 'custom_components/display_studio'


def generated_source():
    source = (ROOT / 'www/runtime/cards.js').read_text(encoding='utf-8')
    spec = json.loads(re.search(
        r'/\* HOME_SPEC_BEGIN \*/(.*?)/\* HOME_SPEC_END \*/', source
    ).group(1))
    return ('"""Generated by scripts/generate_home_spec.py; do not edit by hand."""\n'
            + 'SPEC = ' + pformat(spec, width=100, sort_dicts=False) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'home_spec.py'
    source = generated_source()
    if args.check:
        if not target.exists() or target.read_text(encoding='utf-8') != source:
            parser.error('home_spec.py is stale; run scripts/generate_home_spec.py')
    else:
        target.write_text(source, encoding='utf-8')
